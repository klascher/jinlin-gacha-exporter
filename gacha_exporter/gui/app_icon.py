def app_icon() -> QIcon:
    """返回应用图标；解码失败返回空 QIcon（调用方判 isNull 跳过）。"""
    img = QImage()
    img.loadFromData(base64.b64decode(_ICON_PNG_B64))
    if img.isNull():
        return QIcon()
    pm = QPixmap.fromImage(img)
    icon = QIcon(pm)
    # 明确提供常用尺寸，避免小尺寸下的模糊缩放
    for size in (16, 24, 32, 48, 64, 128, 256):
        icon.addPixmap(pm.scaled(size, size, Qt.AspectRatioMode.IgnoreAspectRatio,
                                 Qt.TransformationMode.SmoothTransformation), QIcon.Mode.Normal, QIcon.State.Off)
    return icon
